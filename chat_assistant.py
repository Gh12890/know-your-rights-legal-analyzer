# saying that i stole a goat" -- Section 303 (theft) scored only ~0.362
# on the embeddings, BEHIND Section 274 (summons-case procedure, ~0.376)
# and tied with several noise matches. The answer sometimes mentioned
# 274. For a small set of offences a layperson describes in one plain
# word ("stole", "cheated"), the right BNS section is not a guess -- so
# anchor it deterministically, exactly like an explicitly-typed section
# number, rather than hoping the embedding ranks it first. Checked in
# order, first hit wins (so "attempt to murder" resolves before
# "murder"). Kept deliberately short and high-precision -- only words
# that map to ONE offence unambiguously when someone is describing an
# accusation against them.
_OFFENCE_KEYWORD_ANCHORS = [
    (re.compile(r"\b(attempt(ed|ing)?\s+to\s+murder|tried\s+to\s+kill)\b", re.I), "109"),
    (re.compile(r"\b(murder(ed|ing)?|killed\s+(him|her|someone|a\s+(man|woman|person)))\b", re.I), "103"),
    (re.compile(r"\b(sto(le|len)|steal(ing)?|theft|thief|shoplift\w*)\b", re.I), "303"),
    (re.compile(r"\b(cheat(ed|ing)?|defraud\w*)\b", re.I), "318"),
    (re.compile(r"\b(extort\w*|blackmail\w*)\b", re.I), "308"),
    (re.compile(r"\b(robbery|robbed|mugg\w*)\b", re.I), "309"),
    (re.compile(r"\b(criminal\s+breach\s+of\s+trust|misappropriat\w*|embezzl\w*)\b", re.I), "316"),
    (re.compile(r"\b(kidnap\w*|abduct\w*)\b", re.I), "137"),
    (re.compile(r"\b(rape|raped|raping)\b", re.I), "64"),
    (re.compile(r"\b(forg(ed|ery|ing)|fake\s+(document|signature|cheque))\b", re.I), "336"),
    (re.compile(r"\b(defam\w*)\b", re.I), "356"),
    (re.compile(r"\b(criminal\s+intimidation|threaten\w*\s+to\s+(kill|hurt|harm))\b", re.I), "351"),
]


def _bns_section_as_match(num: str) -> "dict | None":
    """Build a prompt-ready match dict for a BNS section number: its real
    statute text plus the BNS_SECTION_DATA cognizable/bailable
    enrichment. Shared by _explicit_section_matches (typed section
    numbers) and _offence_keyword_matches (offence words). None if the
    section doesn't resolve."""
    from retrieval import get_statute_section

    data = get_statute_section("BNS", num)
    if not data:
        return None
    return {
        "act": data["act"],
        "section_number": data["section_number"],
        "text": data["text"],
        "source": "explicit_section_ref",
        "all_variants": _bns_section_variants(data["section_number"]),
    }


def _offence_keyword_matches(question: str) -> list:
    """At most ONE anchor -- the first _OFFENCE_KEYWORD_ANCHORS pattern
    the question matches -- as a high-confidence statute match. Deliberately
    capped at one: a person's message usually describes a single alleged
    offence, and firing several would recreate the laundry-list problem
    this is meant to fix."""
    for pat, num in _OFFENCE_KEYWORD_ANCHORS:
        if pat.search(question or ""):
            m = _bns_section_as_match(num)
            return [m] if m else []
    return []


def _bns_section_variants(sec_key: str) -> dict:
    """Every BNS_SECTION_DATA entry for a bare section number, keyed by
    subsection (e.g. '318' -> {'318(1)':..., '318(2)':..., '318(3)':...,
    '318(4)':...}), plus the bare key itself if BNS_SECTION_DATA has a
    genuine bare-key entry. Same lookup semantic_retrieval.
    find_relevant_sections() does inline; factored out here so both the
    real-time lookup and _find_cognizable_bailable_mismatches' ground
    truth use the identical logic (no drift between what fed the prompt
    and what verifies the answer)."""
    try:
        from main import BNS_SECTION_DATA
    except ImportError:
        return {}
    exact = BNS_SECTION_DATA.get(sec_key)
    variants = {k: v for k, v in BNS_SECTION_DATA.items()
                if k == sec_key or k.startswith(f"{sec_key}(")}
    if exact is not None and sec_key not in variants:
        variants[sec_key] = exact
    return variants


def _old_code_equivalents(text: str) -> list:
    """Every old IPC/CrPC section number quoted in `text`, paired with its
    modern BNS/BNSS equivalent from statute_concordance (a checked lookup,
    no LLM). Each item: {'old': 'IPC 420', 'new': 'BNS 318(4)',
    'changed': bool} -- or 'new': None for a provision repealed with no
    re-enacted successor. Deduped, in first-seen order. [] if none.

    Thin wrapper over statute_concordance.scan_old_refs (the shared
    primitive, also used by draft_layer.py's templates); kept here for
    format_retrieved_text_for_prompt and app.py's 'what I found' expander,
    both of which import this name."""
    try:
        from statute_concordance import scan_old_refs
    except Exception:
        return []
    return scan_old_refs(text)


def _old_code_refs_note(text: str) -> str:
    """ONE compact line mapping the old IPC/CrPC section numbers quoted in
    `text` to their modern equivalents, or '' if there are none.

    Deliberately terse and non-imperative -- an earlier multi-line,
    "you MUST use the modern number" version measurably crowded other
    points out of the answer (goat-theft eval regressed on the
    grounds-of-arrest / 24-hour checks, 2026-09-02). The generation
    prompt already bars old-code output; this only needs to supply the
    mapping so the model can comply accurately."""
    eqs = _old_code_equivalents(text)
    if not eqs:
        return ""

    def _tidy(new):
        # "BNSS 35(3); BNSS 35(4); BNSS 35(5); BNSS 35(6)" -> "BNSS 35(3)-(6)"
        tgts = new.split("; ")
        acts = {t.split()[0] for t in tgts}
        bares = {t.split()[1].split("(")[0] for t in tgts}
        if len(tgts) > 2 and len(acts) == 1 and len(bares) == 1:
            subs = [t.split("(")[1].rstrip(")") for t in tgts if "(" in t]
            if len(subs) == len(tgts):
                return f"{tgts[0].split()[0]} {bares.pop()}({subs[0]})-({subs[-1]})"
        return new

    live = [f"{e['old']} -> {_tidy(e['new'])}" for e in eqs if e["new"]]
    gone = [e["old"] for e in eqs if e["new"] is None]
    parts = []
    if live:
        parts.append("current equivalents " + ", ".join(live))
    if gone:
        parts.append("not re-enacted: " + ", ".join(gone))
    return ("\n\n[Section-number note (the text above cites the pre-2024 codes): "
            + "; ".join(parts) + "]")


def format_retrieved_text_for_prompt(matches):
    """Formats a list of enriched match dicts (from
    semantic_retrieval.find_relevant_sections) into plain text suitable
    for feeding into generate_grounded_response -- keeps this formatting
    logic in one place rather than duplicated at each call site.

    CONFIRMED REAL BUG CHAIN (2026-08-27), found via a real failed
    answer to "can police arrest directly for cheating?":
    1. Raw BNS statute text (what "text" contains here) does NOT state
       whether an offence is cognizable/non-cognizable -- confirmed by
       reading Section 318's full embedded text directly: it defines
       cheating and its punishment tiers (318(1)-(4)) but never uses the
       words "cognizable" anywhere. That classification lives only in
       the BNSS First Schedule, a separate document cross-referenced to
       build bns_final_merged_table.json -- it was never part of what
       got embedded.
    2. find_relevant_sections() ALREADY fetches this missing information
       correctly, via BNS_SECTION_DATA lookups into each match's
       "section_data" / "all_variants" fields -- but this function
       previously ignored those fields entirely and only passed the raw
       statute text, so the model never received the one fact it needed
       to actually answer the question, even though retrieval had
       already found it.
    Fixed by including each match's structured compliance data (when
    available) alongside its raw text.

    CONFIRMED REAL BUG (2026-08-28), found while wiring in
    statute_doctrine_map.py's curated overrides for BNSS 43(5): this
    function had NO handling for a "context_note" field. Curated
    statute overrides (source="curated_override") carry a hand-verified
    legal nuance in this field -- e.g. the Madurai Bench ruling that
    BNSS 43(5) is directory, not mandatory -- that doesn't exist
    anywhere in the raw statute text itself and can't be derived from
    all_variants (which is BNS_SECTION_DATA compliance-table data, a
    different thing). Without this fix, a curated override's match dict
    passed through this function silently, produced no error, and
    LOST the one piece of information the override existed to add --
    the LLM prompt only ever saw the bare Section 43 text, never the
    curated nuance. Caught by tracing the real function against the
    real dict shape before integration, not discovered via a runtime
    error (there wasn't one -- this was a silent, no-crash omission).
    Fixed by adding an explicit context_note block, kept separate from
    the all_variants block since it's a conceptually different kind of
    addition (hand-written legal nuance vs. structured compliance-table
    data).

    CONFIRMED REAL BUG (2026-08-29), found via a real user question
    ("when can police file charges of attempt to murder"): the
    multi-condition extraction regex (r'less than ([\\d,]+) rupees') was
    written specifically for Section 303's theft threshold and was the
    ONLY extraction pattern this function knew. Section 109(1)'s two
    conditions (a "general" case vs. "if such act causes hurt to any
    person") have NO rupee threshold at all -- the distinction is a
    plain descriptive condition, not a numeric one. Since the regex
    correctly found no match, extracted_facts stayed empty, and the
    code fell through to the generic "a real exception exists that this
    system could not cleanly extract" fallback -- FALSELY implying
    missing information, when the actual condition text
    ("if such act causes hurt to any person") was sitting right there,
    perfectly readable, in raw_text_preview the entire time. This
    produced a confusing, inaccurate response: the model correctly
    described BOTH conditions (10 years general; life imprisonment if
    hurt caused) using the raw statute text, then ALSO added a false
    caveat from this fallback message claiming an exception existed
    that couldn't be captured -- self-contradictory, and confusing for
    a layperson under stress.

    Fixed by generalizing extraction: first try the rupee-threshold
    pattern (Section 303-style), and if that doesn't match, fall back
    to using the condition's own descriptive label directly (Section
    109-style) -- extracting a clean, short version of the actual
    distinguishing fact from raw_text_preview's leading condition
    description, rather than assuming every multi-condition section
    follows the same shape as theft's value exception. The TRUE
    unresolved fallback (genuinely uninterpretable raw_text_preview,
    e.g. garbled beyond any recognizable condition) is now reserved for
    cases where NEITHER pattern extracts anything usable -- not the
    default whenever the specific rupee-regex happens not to match."""
    blocks = []
    for m in matches:
        label = m.get("section_number") or m.get("paragraph_number") or m.get("chunk_id")
        if m.get("case_name"):
            source = m["case_name"]
        elif m.get("act"):
            source = f"{m['act']} Section {label}"
        else:
            source = f"Section {label}"

        block = f"[{source}, Section/Para {label}]\n{m['text']}"

        if m.get("context_note"):
            block += "\n\n[Important legal context for this section]\n" + m["context_note"]

        # PROJECT 2 (citation_currency.py): judgment matches (identified by
        # case_name) get a currency check the same way statute matches get
        # all_variants/context_note enrichment below. This is a lookup only
        # -- the LLM is told the already-decided currency fact and asked to
        # phrase it, exactly like context_note, never asked to judge
        # currency itself.
        if m.get("case_name"):
            from citation_currency import get_citation_currency_for_case_name
            currency_records = get_citation_currency_for_case_name(m["case_name"])
            # Only the PLAIN-LANGUAGE user_facing_note reaches the model
            # here. 'successor_treatment'/'verified_note' are auditor
            # trails (dates, IK tids, "worked example") -- feeding those
            # in produced hand-wringing "treat this judgment with
            # caution" paragraphs in real answers (2026-09-01 eval).
            # GOOD_LAW entries have user_facing_note=None and are skipped.
            notes = [
                r["user_facing_note"] for r in currency_records
                if r["status"] != "GOOD_LAW" and r.get("user_facing_note")
            ]
            if notes:
                block += (
                    "\n\n[Currency note -- if this case is central to your answer, work this "
                    "in as ONE short plain clause; if the case is only a minor mention, you "
                    "may leave it out]\n" + "\n".join(dict.fromkeys(notes))
                )

        variants = m.get("all_variants") or {}
        if variants:
            variant_lines = []
            for variant_key, variant_data in sorted(variants.items()):
                cog = variant_data.get("cognizable")
                bail = variant_data.get("bailable")
                years = variant_data.get("max_years")
                has_multiple = variant_data.get("has_multiple_conditions")
                line = f"  - {variant_key}: cognizable={cog}, bailable={bail}, max_years={years}"
                if has_multiple:
                    conditions = variant_data.get("all_conditions", [])
                    extracted_facts = []
                    for cond in conditions:
                        preview = cond.get("raw_text_preview", "")

                        # PATTERN 1 (original, Section 303-style): a
                        # numeric rupee threshold with an optional
                        # return/restoration qualifier.
                        threshold_match = re.search(r'less than ([\d,]+) rupees', preview)
                        if threshold_match:
                            mentions_return = "return" in preview.lower() or "restoration" in preview.lower()
                            fact = f"if the value of the property is less than Rs. {threshold_match.group(1)}"
                            if mentions_return:
                                fact += " and the property is returned/restored"
                            fact += f", this becomes: cognizable={cond.get('cognizable')}, bailable={cond.get('bailable')}"
                            extracted_facts.append(fact)
                            continue

                        # PATTERN 2 (NEW, Section 109-style): no numeric
                        # threshold, but the condition itself carries a
                        # short, real, plain-language description (e.g.
                        # "If such act causes hurt to any person") --
                        # this is exactly what the "condition" field
                        # already stores for such entries. Use it
                        # directly rather than treating its absence from
                        # Pattern 1 as "nothing could be extracted".
                        condition_desc = cond.get("condition", "")
                        is_generic_label = condition_desc.strip().lower() in ("general", "")
                        if condition_desc and not is_generic_label:
                            # condition_desc can itself be a multi-line
                            # raw preview fragment (confirmed real case:
                            # 109(1)'s second condition's "condition"
                            # field is "If such act causes hurt to\n
                            # Imprisonment for life, or\nCognizable...\n
                            # C" -- truncated mid-word). Take only the
                            # first line, which reliably holds the real
                            # descriptive clause before the punishment/
                            # classification columns begin.
                            first_line = condition_desc.split("\n")[0].strip()
                            if first_line and first_line.lower() != "general":
                                fact = (
                                    f"in the specific situation described as \"{first_line}\", "
                                    f"this becomes: cognizable={cond.get('cognizable')}, "
                                    f"bailable={cond.get('bailable')}"
                                )
                                extracted_facts.append(fact)

                    if extracted_facts:
                        line += (
                            " -- NOTE: this section has multiple conditions, confirmed from the "
                            "source data: " + "; ".join(extracted_facts) + ". State these specific "
                            "conditions as known facts -- do not tell the user these details are "
                            "unavailable or that an exception exists which couldn't be captured, "
                            "since the conditions ARE available and listed here. Do not add any "
                            "OTHER condition beyond what is stated here."
                        )
                    else:
                        # Genuine fallback: multiple conditions exist,
                        # NEITHER extraction pattern found anything
                        # usable in raw_text_preview -- here, and only
                        # here, is uncertainty actually honest.
                        line += (
                            " -- NOTE: this section has MULTIPLE conditions; the above is the "
                            "general-case classification only, and a real exception exists that "
                            "this system could not cleanly extract. Tell the user a specific "
                            "exception exists and to confirm the exact threshold with a lawyer."
                        )
                variant_lines.append(line)
            block += "\n\n[Known classification for this section, from the verified compliance table]\n" + "\n".join(variant_lines)

        blocks.append(block)

    joined = "\n\n---\n\n".join(blocks)
    # ONE consolidated old->new section-number note for the whole prompt
    # (not per-block: the case law repeats "Section 41 CrPC" across
    # several paragraphs, and repeating the mapping each time crowded the
    # answer -- see _old_code_refs_note).
    joined += _old_code_refs_note(joined)
    return joined

def answer_question(question):
    """Main entry point for the chat interface. Returns a dict describing
    the outcome, always including a 'state' field so the UI layer can
    render each case distinctly and honestly, per this project's
    established "surface uncertainty, don't silently guess" principle
    throughout every other retrieval layer built this session.

        Possible states:
      'unrelated'          -- not a legal question, redirected politely
      'covered_elsewhere_in_tool' -- about bank freezing or cheque bounce,
                               which this chat feature's corpus doesn't
                               cover yet, but the wider tool genuinely
                               handles via document upload -- redirected
                               there, not told "not covered"
      'adjacent_uncovered'  -- real legal question, but outside what this
                               tool covers anywhere (BNS/BNSS chat scope
                               or the document-upload domains)
      'classifier_unavailable' -- couldn't even classify the question
      'no_match'           -- in scope, but nothing in the corpus cleared
                               the similarity threshold, AND no curated
                               statute override matched either
      'single_match'       -- one coherent, agreeing set of matches
      'conflicting_matches' -- multiple matches that disagree on a key
                               legal attribute (e.g. cognizability) --
                               never silently picks one
      'retrieval_unavailable' -- embeddings aren't set up (no API key,
                               no embeddings file, etc.)

    FIXED 2026-08-28: the conflicting_matches branch was previously
    nested INSIDE the no_match check's if-block (an indentation bug),
    making it unreachable -- since no_match returns immediately on its
    own condition, the nested conflicting_matches check could only ever
    fire if result["state"] was simultaneously "no_match" AND
    "conflicting_matches", which never happens. Real consequence: a
    genuine conflicting-matches result was silently falling through to
    the single_match handling below, mislabeling a conflict as a clean
    match. Fixed by making conflicting_matches a proper sibling
    elif, checked before the single_match fallthrough.

    ADDED 2026-08-28: a curated statute doctrine override check
    (statute_doctrine_map.py), covering known gaps where semantic
    search under-retrieves a specific high-stakes statute section
    (currently: BNSS 43(5), night-arrest-of-women safeguard, which
    scores ~0.343 against real "arrested at night" queries --
    indistinguishable from the confirmed-irrelevant ceiling ~0.339,
    per this project's own Aug 27 calibration data). This check runs
    BEFORE the normal semantic-search state handling, so it applies
    regardless of what score semantic search assigns -- it's a
    deliberate bypass for specific, known, verified gaps, not a
    replacement for semantic search generally. See
    statute_doctrine_map.py's module docstring for full reasoning and
    scope limits.
    """
    from semantic_retrieval import find_relevant_sections
    from statute_doctrine_map import get_statute_doctrine_override

    category, reasoning, redirect_domain = classify_scope(question)

    if category is None:
        return {"state": "classifier_unavailable"}

    if category == "unrelated":
        return {"state": "unrelated"}

    if category == "covered_elsewhere_in_tool":
        return {"state": "covered_elsewhere_in_tool", "reasoning": reasoning, "redirect_domain": redirect_domain}

    if category == "adjacent_uncovered":
        return {"state": "adjacent_uncovered", "reasoning": reasoning}

    # category == "in_scope" from here on

    # Curated statute override check -- runs BEFORE normal semantic
    # retrieval's state handling, so a known high-stakes gap (like
    # BNSS 43(5)) surfaces even if the embedding score alone wouldn't
    # clear SIMILARITY_THRESHOLD. This does NOT replace semantic
    # search -- both run, and both sets of results get combined below.
    statute_overrides = get_statute_doctrine_override(question)

    # Explicit-section lookup: if the person literally names a section
    # ("what is section 318 of BNS", "does BNS 303 apply"), pull that
    # section's real text directly. Confirmed real gap (2026-09-01 eval):
    # "what is section 318 of BNS" scored below threshold on every
    # embedded chunk and returned no_match -- a plainly answerable
    # question producing an empty answer. Merged into statute_overrides
    # so it flows through the same combine-and-fallback logic below.
    explicit = _explicit_section_matches(question)
    if explicit:
        seen = {(o.get("act"), o.get("section_number")) for o in statute_overrides}
        statute_overrides = statute_overrides + [
            e for e in explicit if (e["act"], e["section_number"]) not in seen
        ]

    # Offence-keyword anchor: only when the person did NOT name a section
    # themselves (explicit lookup already covers that) -- if their message
    # describes an accusation in one plain word ("stole", "cheated"),
    # anchor the matching BNS offence deterministically instead of hoping
    # the embedding ranks it first. Confirmed real gap (2026-09-01 live):
    # "arrested me... saying that i stole a goat" scored Section 303 at
    # ~0.36, behind a procedural noise match. Flows through the same
    # combine-and-fallback logic below as every other statute override.
    if not explicit:
        seen = {(o.get("act"), o.get("section_number")) for o in statute_overrides}
        statute_overrides = statute_overrides + [
            m for m in _offence_keyword_matches(question)
            if (m["act"], m["section_number"]) not in seen
        ]

    result = find_relevant_sections(question)

    if result["state"] == "unavailable":
        # Even if retrieval is unavailable, a curated override may
        # still apply -- don't discard it just because the general
        # embedding-based path is down.
        if statute_overrides:
            retrieved_text = format_retrieved_text_for_prompt(statute_overrides)
            response_text = generate_grounded_response(question, retrieved_text, matches=statute_overrides)
            return {
                "state": "single_match",
                "matches": statute_overrides,
                "response_text": response_text,
            }
        return {"state": "retrieval_unavailable"}

    if result["state"] == "no_match":
        # A curated override can still provide an answer even when
        # normal semantic search found nothing above threshold --
        # this is the exact scenario the override exists for.
        if statute_overrides:
            retrieved_text = format_retrieved_text_for_prompt(statute_overrides)
            response_text = generate_grounded_response(question, retrieved_text, matches=statute_overrides)
            return {
                "state": "single_match",
                "matches": statute_overrides,
                "response_text": response_text,
            }
        return {"state": "no_match"}

    if result["state"] == "conflicting_matches":
        all_matches = result["matches"] + result.get("judgment_matches", []) + statute_overrides
        retrieved_text = format_retrieved_text_for_prompt(all_matches)
        response_text = generate_grounded_response(question, retrieved_text, is_conflict=True, matches=all_matches)
        return {
            "state": "conflicting_matches",
            "matches": all_matches,
            "response_text": response_text,
            "situation_detected": _looks_like_situation(response_text),
        }

    # single_match -- combine statute matches with judgment matches
    # (confirmed real fix: previously judgment_matches were computed by
    # find_relevant_sections but never actually used here, so case law
    # like Arnesh Kumar never reached the response generator even when
    # it was the single highest-scoring result overall) AND any
    # curated statute overrides that matched alongside the normal
    # semantic results.
    all_matches = result["matches"] + result.get("judgment_matches", []) + statute_overrides
    retrieved_text = format_retrieved_text_for_prompt(all_matches)
    response_text = generate_grounded_response(question, retrieved_text, matches=all_matches)
    return {
        "state": "single_match",
        "matches": all_matches,
        "response_text": response_text,
        "situation_detected": _looks_like_situation(response_text),
    }