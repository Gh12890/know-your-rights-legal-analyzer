"""
Chat assistant for laymen asking open-ended questions in plain language.

This is the wiring layer that connects a user's free-text question to the
retrieval infrastructure already built this session -- semantic_retrieval.py
(real embeddings, scored, with conflict detection) and retrieval.py (exact
lookup for judgment doctrines). It does NOT introduce any new way of
deciding legal correctness: every answer either quotes real retrieved text
directly, or is generated by Claude with strict instructions to use ONLY
that retrieved text -- never to answer from general knowledge, never to
invent a section number or holding.

Flow, and why each step exists:
  1. Scope classification (cheap Haiku call) -- decides whether a question
     is plausibly about BNS/BNSS arrest/FIR procedure at all, BEFORE
     spending an embedding call on it. Confirmed necessity: a layman will
     ask genuinely anything ("how do I sue my neighbour", "is this legal",
     small talk) and semantic search always returns SOMETHING, even for
     completely unrelated questions -- classification catches the "this
     isn't even the right kind of question" case before retrieval ever
     runs, rather than relying on the similarity threshold alone to catch
     every kind of irrelevance.
  2. Semantic retrieval (only for in-scope questions) -- real embeddings,
     real similarity scores, real conflict detection (see
     semantic_retrieval.py's docstring for the confirmed "rioting" case
     this specifically guards against).
  3. Response generation -- Claude reads ONLY the retrieved real text and
     is instructed never to go beyond it. This keeps the same
     deterministic-grounding guarantee the rest of this project relies on:
     the LLM explains and phrases, it does not decide or invent.
     CONFIRMED (2026-09-01) the instruction alone is not a hard
     guarantee -- a real, low-frequency (~1/10 trials) case slipped
     through where the model named a real BNSS section it was never
     actually given for that query. generate_grounded_response() now
     deterministically checks its own output against retrieved_text
     (see _find_ungrounded_sections) and retries once before ever
     showing an unverified claim -- the LLM proposes, Python verifies.

Every response also carries a plain-language "what to do next" pointer,
per the explicit design goal that this tool should act as a guide/advisor
for a layman, not just answer-and-stop.
"""

